"""Per-provider request adapters: make one conversation portable across providers.

Cross-provider failover mid-conversation means a request to provider B can contain tool calls that
were generated by provider A. "OpenAI-compatible" APIs disagree on the details, so each provider gets
a small, pure function that rewrites the outgoing JSON payload just before it's sent:

* **Mistral** only accepts tool-call ids of exactly 9 characters ``[a-zA-Z0-9]`` and uses
  ``max_tokens`` (not ``max_completion_tokens``). Foreign ids are deterministically re-hashed, so the
  same original id always maps to the same Mistral id. Assistant calls and their tool results stay paired
  across turns with no stored state.
* **Gemini** (thinking models, OpenAI-compatible endpoint) rejects function calls in the history that
  lack a ``thought_signature``. Calls made by other providers never have one, and the LangChain
  OpenAI client drops Gemini's own. Google documents a placeholder signature for histories transferred
  from other models, which we attach where missing.
* **Custom** endpoints (vLLM, Ollama, …) get ``max_tokens``, the most widely supported spelling.

Adapters are applied through :class:`AdaptedChatOpenAI`, a ``ChatOpenAI`` subclass that post-processes
``_get_request_payload``.
"""

from __future__ import annotations

import hashlib
import re
import string
from collections.abc import Callable
from typing import Any

from langchain_openai import ChatOpenAI
from pydantic import Field

PayloadAdapter = Callable[[dict[str, Any]], dict[str, Any]]

#: Placeholder documented by Google for function calls whose real thought signature is unavailable
#: (e.g. conversation history produced by another model).
GEMINI_PLACEHOLDER_SIGNATURE = "skip_thought_signature_validator"

_MISTRAL_ID_RE = re.compile(r"^[A-Za-z0-9]{9}$")
_ALPHABET = string.ascii_letters + string.digits


def _use_max_tokens(payload: dict[str, Any]) -> dict[str, Any]:
    """Rename ``max_completion_tokens`` -> ``max_tokens`` (unless both are present)."""
    if "max_completion_tokens" in payload and "max_tokens" not in payload:
        payload["max_tokens"] = payload.pop("max_completion_tokens")
    return payload


def mistral_tool_call_id(original: str) -> str:
    """Deterministic 9-char alphanumeric id accepted by Mistral.

    >>> mistral_tool_call_id("abcDEF123")  # already valid -> unchanged
    'abcDEF123'
    >>> len(mistral_tool_call_id("call_8f3kd92jf83kd9fj3k2l")), mistral_tool_call_id("x") == mistral_tool_call_id("x")
    (9, True)
    """
    if _MISTRAL_ID_RE.match(original or ""):
        return original
    n = int.from_bytes(hashlib.sha1((original or "").encode()).digest(), "big")
    chars = []
    for _ in range(9):
        n, r = divmod(n, len(_ALPHABET))
        chars.append(_ALPHABET[r])
    return "".join(chars)


def mistral_adapter(payload: dict[str, Any]) -> dict[str, Any]:
    """Re-key foreign tool-call ids and use ``max_tokens``."""
    for msg in payload.get("messages", []):
        for call in msg.get("tool_calls") or []:
            if "id" in call:
                call["id"] = mistral_tool_call_id(call["id"])
        if msg.get("role") == "tool" and "tool_call_id" in msg:
            msg["tool_call_id"] = mistral_tool_call_id(msg["tool_call_id"])
    return _use_max_tokens(payload)


def gemini_adapter(payload: dict[str, Any]) -> dict[str, Any]:
    """Attach a thought signature to historical function calls that lack one; use ``max_tokens``."""
    for msg in payload.get("messages", []):
        for call in msg.get("tool_calls") or []:
            google = call.setdefault("extra_content", {}).setdefault("google", {})
            google.setdefault("thought_signature", GEMINI_PLACEHOLDER_SIGNATURE)
    return _use_max_tokens(payload)


ADAPTERS: dict[str, PayloadAdapter] = {
    "mistral": mistral_adapter,
    "gemini": gemini_adapter,
    "custom": _use_max_tokens,
}


class AdaptedChatOpenAI(ChatOpenAI):
    """``ChatOpenAI`` whose outgoing payload is rewritten by a provider adapter."""

    payload_adapter: Any = Field(default=None, exclude=True)

    def _get_request_payload(self, input_: Any, *, stop: list[str] | None = None, **kwargs: Any) -> dict:
        payload = super()._get_request_payload(input_, stop=stop, **kwargs)
        return self.payload_adapter(payload) if self.payload_adapter else payload
